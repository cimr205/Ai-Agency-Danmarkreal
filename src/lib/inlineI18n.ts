export function tl(locale: Locale | string, da: string, en: string): string {
  if (locale === 'da') return da;
  if (locale === 'de') return DE[en] ?? en;
  return en;
}

/** tl() with the locale taken from the URL (/:locale/app/…) — for helper
 *  components and plain functions that don't have useI18n() in scope. */
export function tx(da: string, en: string): string {
  return tl(getLocaleFromPath(), da, en);
}

/** All three languages inline — for sentences with interpolated values,
 *  which can't be looked up in the German dictionary. */
export function t3(da: string, en: string, de: string, locale: Locale | string = getLocaleFromPath()): string {
  return locale === 'da' ? da : locale === 'de' ? de : en;
}

/** BCP-47 tag for Intl/toLocale*String that follows the app locale, not the browser. */
export function dateLocaleTag(locale: Locale | string = getLocaleFromPath()): string {
  return locale === 'da' ? 'da-DK' : locale === 'de' ? 'de-DE' : 'en-GB';
}
