// Restores an ORIGIN logical backup into an EMPTY, isolated database and verifies it:
// row counts and checksums per table, constraints, policies, RLS flags, functions, and tenant isolation.
// Never point TARGET_URL at production: the script refuses a target that already has tables.
// Usage: TARGET_URL=postgres://localhost/restore_test node restore-verify.mjs backup.json
import pg from 'pg';
import fs from 'fs';

const b = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const c = new pg.Client({ connectionString: process.env.TARGET_URL, ssl: false });
await c.connect();
const q = (sql, p) => c.query(sql, p);
const id = (s) => c.escapeIdentifier(s);
const role = (r) => (r === 'PUBLIC' || r === 'public' ? 'PUBLIC' : id(r));

if ((await q(`SELECT count(*)::int n FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind = 'r'`)).rows[0].n > 0) {
  console.error('target already has tables in public: refusing to restore'); process.exit(2);
}

await q("BEGIN; SET LOCAL TimeZone = 'UTC'");
for (const r of b.roles) {
  const exists = (await q('SELECT 1 FROM pg_roles WHERE rolname = $1', [r.name])).rowCount;
  if (!exists) await q(`CREATE ROLE ${id(r.name)} NOLOGIN ${r.bypassrls ? 'BYPASSRLS' : 'NOBYPASSRLS'}`); // restored without login or password
}
await q(`GRANT USAGE ON SCHEMA public TO ${b.roles.map((r) => id(r.name)).join(', ') || 'PUBLIC'}`);
for (const e of b.enums) await q(`CREATE TYPE ${id(e.name)} AS ENUM (${e.labels.map((l) => c.escapeLiteral(l)).join(', ')})`);
for (const s of b.sequences.filter((s) => !s.identity)) await q(`CREATE SEQUENCE ${id(s.name)} AS ${s.type} INCREMENT ${s.increment_by} START ${s.start_value}`);
for (const t of b.tables) {
  const cols = t.columns.map((col) => {
    let d = `${id(col.name)} ${col.type}`;
    if (col.identity === 'a') d += ' GENERATED ALWAYS AS IDENTITY';
    else if (col.identity === 'd') d += ' GENERATED BY DEFAULT AS IDENTITY';
    else if (col.default) d += ` DEFAULT ${col.default}`;
    if (col.notnull) d += ' NOT NULL';
    return d;
  });
  await q(`CREATE TABLE ${id(t.name)} (${cols.join(', ')})`);
}
for (const s of b.sequences.filter((s) => !s.identity && s.owned_by)) await q(`ALTER SEQUENCE ${id(s.name)} OWNED BY ${s.owned_by}`);
for (const t of b.tables) {
  const override = t.columns.some((col) => col.identity === 'a') ? 'OVERRIDING SYSTEM VALUE' : '';
  await q(`INSERT INTO ${id(t.name)} ${override} SELECT * FROM jsonb_populate_recordset(NULL::${id(t.name)}, $1::jsonb)`, [t.data]);
}
for (const s of b.sequences) {
  if (s.last_value == null) continue;
  const seq = s.identity ? (await q(`SELECT pg_get_serial_sequence($1, $2) s`, s.owned_by.split('.'))).rows[0].s : id(s.name);
  await q(`SELECT setval($1, $2, true)`, [seq, s.last_value]);
}
for (const k of b.constraints) await q(`ALTER TABLE ${k.table} ADD CONSTRAINT ${id(k.name)} ${k.def}`);
for (const i of b.indexes) await q(i.def);
for (const f of b.functions) {
  await q(f.def);
  await q(`ALTER FUNCTION ${f.signature} OWNER TO ${id(f.owner)}`);
  if (f.has_acl) await q(`REVOKE ALL ON FUNCTION ${f.signature} FROM PUBLIC`);
  for (const g of f.execute_grantees) await q(`GRANT EXECUTE ON FUNCTION ${f.signature} TO ${role(g)}`);
}
for (const tr of b.triggers) await q(tr.def);
for (const t of b.tables) {
  if (t.rls) await q(`ALTER TABLE ${id(t.name)} ENABLE ROW LEVEL SECURITY`);
  if (t.force_rls) await q(`ALTER TABLE ${id(t.name)} FORCE ROW LEVEL SECURITY`);
  for (const g of t.grants) await q(`GRANT ${g.privilege} ON ${id(t.name)} TO ${role(g.grantee)}`);
  for (const g of t.column_grants) await q(`GRANT ${g.privilege} (${id(g.column)}) ON ${id(t.name)} TO ${role(g.grantee)}`);
}
for (const g of b.sequence_grants) await q(`GRANT ${g.privilege} ON SEQUENCE ${id(g.sequence)} TO ${role(g.grantee)}`);
for (const p of b.policies) {
  await q(`CREATE POLICY ${id(p.name)} ON ${id(p.table)} AS ${p.permissive} FOR ${p.cmd} TO ${p.roles.map(role).join(', ')}`
    + (p.qual ? ` USING (${p.qual})` : '') + (p.with_check ? ` WITH CHECK (${p.with_check})` : ''));
}
await q('COMMIT');

// ---- verification
let ok = 0, fail = 0;
const check = (cond, msg) => { cond ? ok++ : fail++; console.log((cond ? 'PASS ' : 'FAIL ') + msg); };
await q("SET TimeZone = 'UTC'");
for (const t of b.tables) {
  const r = (await q(`SELECT count(*)::int n, md5(coalesce(string_agg(x::text, '|' ORDER BY x::text COLLATE "C"), '')) md5 FROM ${id(t.name)} x`)).rows[0];
  check(r.n === t.checksum.n && r.md5 === t.checksum.md5, `${t.name}: ${r.n} rows, checksum ${r.md5 === t.checksum.md5 ? 'identical' : 'DIFFERENT'}`);
}
const count = async (sql) => (await q(sql)).rows[0].n;
check(await count(`SELECT count(*)::int n FROM pg_constraint WHERE connamespace='public'::regnamespace AND contype IN ('p','u','c','f','x')`) === b.constraints.length, `constraints: ${b.constraints.length}`);
check(await count(`SELECT count(*)::int n FROM pg_policies WHERE schemaname='public'`) === b.policies.length, `policies: ${b.policies.length}`);
check(await count(`SELECT count(*)::int n FROM pg_class WHERE relnamespace='public'::regnamespace AND relkind='r' AND relforcerowsecurity`) === b.tables.filter((t) => t.force_rls).length, 'forced RLS flags');
check(await count(`SELECT count(*)::int n FROM pg_proc WHERE pronamespace='public'::regnamespace AND prokind='f'`) === b.functions.length, `functions: ${b.functions.length}`);
check(await count(`SELECT count(*)::int n FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid WHERE c.relnamespace='public'::regnamespace AND NOT t.tgisinternal`) === b.triggers.length, `triggers: ${b.triggers.length}`);
if (b.roles.some((r) => r.name === 'origin_app')) {
  await q('BEGIN; SET LOCAL ROLE origin_app');
  check((await q('SELECT count(*)::int n FROM jobs')).rows[0].n === 0, 'restored RLS: origin_app without tenant sees 0 jobs');
  await q(`SELECT set_config('app.tenant_id', 'tenant_test', true)`);
  check((await q(`SELECT count(*) FILTER (WHERE tenant_id <> 'tenant_test')::int n FROM jobs`)).rows[0].n === 0, 'restored RLS: tenant_test sees no other tenant');
  check((await q('SELECT count(*)::int n FROM origin_list_automation_tenants()')).rows[0].n >= 1, 'restored scheduler function works for origin_app');
  await q('ROLLBACK');
}
console.log(`\n${ok} passed, ${fail} failed (backup taken ${b.taken_at}, server ${b.server_version})`);
await c.end();
process.exit(fail ? 1 : 0);
